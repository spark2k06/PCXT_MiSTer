; Test program for sys_video_tb (+mph): the instruction sequence that 8088 MPH
; times at start-up to decide whether it is running on a 4.77 MHz 8088, run from
; RAM with the real chipset around it, timed with the 8253 channel 0 as the demo
; does, once with the DMA refresh masked and once with it running.
;
;   nasm -f bin sys_mph_prog.asm -o sys_mph_prog.bin
;   python3 mkhex.py sys_mph_prog.bin sys_mph_prog.hex
;
; Result, in RAM: 0000:0608 = ticks (1.19 MHz) with the refresh DMA masked,
;                 0000:060A = ticks with the refresh DMA running,
;                 0000:0602 = BEEF when the program is done.
; The sequence is the body of the routine in 8088MPH.EXE (offsets 0014..034E of
; its code, after unpacking); it ends here with a RETF.
