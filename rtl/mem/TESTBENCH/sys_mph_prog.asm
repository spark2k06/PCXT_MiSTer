    mov     al, 0x04
    out     0x0A, al
    call    timed
    xor     ax, ax
    mov     ds, ax
    mov     [0x0610], dx

    ; ---- refresh running ----
    xor     al, al
    out     0x0A, al                ; unmask channel 0
    call    timed
    xor     ax, ax
    mov     ds, ax
    mov     [0x060A], dx
    mov     ax, [0x0610]
    mov     [0x0608], ax
    mov     word [0x0600], 0
    mov     word [0x0602], 0xBEEF
    hlt
    jmp     $

; DX = elapsed channel 0 ticks across the sequence
timed:
    mov     ax, 0x2000
    mov     ds, ax
    mov     es, ax
    mov     ss, ax
    mov     sp, 0xFFF0
    xor     al, al
    out     0x43, al                ; latch channel 0
