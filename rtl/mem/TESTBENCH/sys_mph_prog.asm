    mov     bl, al
    in      al, 0x40
    mov     bh, al
    push    bx
    xor     bx, bx
    xor     cx, cx
    xor     dx, dx
    xor     si, si
    xor     di, di
    call    0x2000:0x0014
    xor     al, al
    out     0x43, al
    in      al, 0x40
    mov     dl, al
    in      al, 0x40
    mov     dh, al
    pop     bx
    sub     bx, dx
    mov     dx, bx
    xor     ax, ax
    mov     ss, ax
    mov     sp, 0x7BFE
    ret

